import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={window:{}};
vm.runInNewContext(await readFile('assets/glosario.js','utf8'),context);
const entries=context.window.RI_GLOSARIO, search=context.window.RI_BUSCAR_GLOSARIO;
assert.equal(search(entries,'CIDH')[0].id,'cidh');
assert.equal(search(entries,'hecho').length,1);
assert.equal(search(entries,'hecho')[0].id,'hecho');
assert.equal(search(entries,'hechos')[0].id,'hecho');
assert.equal(search(entries,'que es un hecho')[0].id,'hecho');
assert.equal(search(entries,'¿Qué es un hecho?')[0].id,'hecho');
assert.equal(search(entries,'informe preliminar').length,1);
assert.ok(search(entries,'hecho probado').some(x=>x.id==='hecho-probado'));
assert.equal(search(entries,'informe preliminar')[0].id,'informe-preliminar');
for (const id of ['informe-sobre-fondo-cidh','periodo-recomendaciones-estado','notificacion-peticionario-informe','remision-caso-corte','mayoria-absoluta-cidh','deber-buena-fe-recomendaciones','solicitud-suspension-articulo-51','opinion-conclusiones-articulo-51','plazo-medidas-articulo-51-2','evaluacion-medidas-articulo-51','publicacion-informe-articulo-51','solucion-durante-periodo-articulo-51','estado-somete-caso-articulo-51','confidencialidad-informe-articulo-50','plazo-solicitud-suspension-cidh','decision-expresa-cidh','informe-solucion-amistosa-articulo-49','diferencia-articulo-51-1-2','respuesta-no-es-cumplimiento','cumplimiento-parcial-recomendacion','publicacion-por-sometimiento','plazo-informacion-partes-informe-definitivo','documento-vigente-y-version','fecha-de-transmision-informe']) assert.ok(entries.some(x=>x.id===id),`missing glossary concept: ${id}`);
assert.equal(search(entries,'plazo para informar sobre recomendaciones')[0].id,'periodo-recomendaciones-estado');
assert.equal(search(entries,'notificación al peticionario del informe preliminar')[0].id,'notificacion-peticionario-informe');
assert.ok(search(entries,'tres meses desde transmisión del informe preliminar').some(x=>x.id==='periodo-articulo-51'));
assert.equal(search(entries,'plazo para que el Estado tome medidas')[0].id,'plazo-medidas-articulo-51-2');
assert.ok(entries.filter(x=>x.simple).length>=20,'key concepts need plain-language explanations');
assert.ok(entries.filter(x=>x.simple).every(x=>x.example),'plain-language explanations should include a concrete example');
assert.ok(search(entries,'notificacion').some(x=>x.id==='notificacion'));
const incidental={id:'incidental',label:'Otro concepto',aliases:[],definition:'menciona CIDH',use:'',category:'Otro'};
assert.equal(search([incidental],'CIDH').length,0);
assert.equal(search([incidental],'CIDH',{fullText:true}).length,1);
assert.equal(search(entries,'zzzz-no-existe').length,0);
const filtered=search(entries,'',{letter:'R',category:'Competencia y jurisdicción'});
assert.ok(filtered.length>0);
assert.ok(filtered.every(x=>x.label.startsWith('R')&&x.category==='Competencia y jurisdicción'));
assert.equal(search([{...incidental,label:'Niñez'},{...incidental,label:'Ñandú'}],'',{letter:'Ñ'}).length,1);
const all=search(entries);
assert.equal(all.length,entries.length);
assert.ok(all.every((x,i)=>!i||all[i-1].label.localeCompare(x.label,'es')<=0));
const ids=new Set(entries.map(x=>x.id));
assert.equal(ids.size,entries.length,'glossary ids must be unique');
assert.ok(entries.every(x=>(x.source||x.category==='Caso de práctica')&&x.related.every(id=>ids.has(id))),'every legal glossary record needs a source and valid cross-links; fictional practice entries may be source-free');
console.log('Glossary: exact match priority, aliases, accents, alphabet, combined filters, full-text opt-in and empty results passed.');
